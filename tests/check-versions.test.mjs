import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { readVersionInputs, versionProblems } from '../scripts/check-versions.mjs'

const VERSION = '1.0.0-alpha01'

const clean = {
  version: VERSION,
  clientSource: `// Remote Instance ${VERSION}. Generated by scripts/build.mjs; edit src/.\nwindow.__ModuleLoader__.load({ id: "@kaus-io/dsh-remote-instance" });\n`,
  readme: '```sh\ndsh plugin --profile web add @kaus-io/dsh-remote-instance@1.0.0-alpha01\n```\n',
  changelog: `# 更新日志\n\n## ${VERSION}\n\n- 首个版本\n`,
}

describe('readVersionInputs', () => {
  it('checks pinned versions in the separate usage README', async () => {
    const root = await mkdtemp(join(await realpath(tmpdir()), 'dsh-remote-versions-'))
    try {
      await mkdir(join(root, 'docs'))
      await Promise.all([
        writeFile(join(root, 'package.json'), JSON.stringify({ version: VERSION })),
        writeFile(join(root, 'client.js'), clean.clientSource),
        writeFile(join(root, 'README.md'), '### DSH Remote Instance\n\n[传送门](<docs/README.md>)。\n'),
        writeFile(join(root, 'docs', 'README.md'), clean.readme),
        writeFile(join(root, 'CHANGELOG.md'), clean.changelog),
      ])
      const inputs = await readVersionInputs(root)
      assert.match(inputs.readme, /### DSH Remote Instance/)
      assert.deepEqual(versionProblems(inputs), [])
      await writeFile(join(root, 'docs', 'README.md'), clean.readme.replaceAll(VERSION, '0.9.0'))
      assert.match(versionProblems(await readVersionInputs(root))[0], /README\.md pins "0\.9\.0"/)
    } finally {
      assert.equal(await realpath(root), root)
      await rm(root, { recursive: true, force: true })
    }
  })
})

describe('versionProblems', () => {
  it('accepts manifest, build, README, and CHANGELOG in agreement', () => {
    assert.deepEqual(versionProblems(clean), [])
  })

  it('accepts a release tag with or without the v prefix', () => {
    assert.deepEqual(versionProblems({ ...clean, tag: 'v1.0.0-alpha01' }), [])
    assert.deepEqual(versionProblems({ ...clean, tag: '1.0.0-alpha01' }), [])
  })

  it('rejects a tag that names another version', () => {
    const problems = versionProblems({ ...clean, tag: 'v1.0.0-alpha1' })
    assert.equal(problems.length, 1)
    assert.match(problems[0], /release tag "v1\.0\.0-alpha1" does not match/)
  })

  it('rejects a stale build artifact', () => {
    const problems = versionProblems({ ...clean, clientSource: '// Remote Instance 0.9.0. Generated by scripts/build.mjs; edit src/.\n' })
    assert.equal(problems.length, 1)
    assert.match(problems[0], /client\.js was built for "0\.9\.0"/)
  })

  it('rejects a build artifact with no banner at all', () => {
    assert.match(versionProblems({ ...clean, clientSource: 'window.x = 1\n' })[0], /no build banner/)
  })

  it('rejects a README that pins another version', () => {
    const problems = versionProblems({ ...clean, readme: 'dsh plugin add @kaus-io/dsh-remote-instance@1.0.0-alpha02' })
    assert.equal(problems.length, 1)
    assert.match(problems[0], /README\.md pins "1\.0\.0-alpha02"/)
  })

  it('rejects a README with no pinned install command', () => {
    assert.match(versionProblems({ ...clean, readme: 'dsh plugin add @kaus-io/dsh-remote-instance@alpha' })[0], /does not show an install command/)
  })

  it('rejects a CHANGELOG whose first entry is another version', () => {
    const problems = versionProblems({ ...clean, changelog: '# 更新日志\n\n## 0.9.0\n\n- old\n' })
    assert.equal(problems.length, 1)
    assert.match(problems[0], /CHANGELOG\.md starts at "0\.9\.0"/)
  })

  it('rejects a CHANGELOG with no entry', () => {
    assert.match(versionProblems({ ...clean, changelog: '# 更新日志\n\n' })[0], /no "## <version>" entry/)
  })

  it('rejects an invalid manifest version before checking anything else', () => {
    const problems = versionProblems({ ...clean, version: '1.0.0alpha01', tag: 'v1.0.0alpha01' })
    assert.equal(problems.length, 1)
    assert.match(problems[0], /not valid SemVer/)
  })

  it('reports every disagreement at once', () => {
    const problems = versionProblems({
      version: VERSION,
      tag: 'v9.9.9',
      clientSource: `// Remote Instance 9.9.9. Generated by scripts/build.mjs; edit src/.\n`,
      readme: '@kaus-io/dsh-remote-instance@8.8.8',
      changelog: '## 7.7.7\n',
    })
    assert.equal(problems.length, 4)
  })
})
