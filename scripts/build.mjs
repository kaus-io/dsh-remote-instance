/**
 * Build the exact artifacts the DSH profile loads.
 *
 * `index.js` is the Host half (plain ESM bundling the sources), `client.js` is
 * the browser half shaped as a CJS bundle registered with the host module
 * table, where React stays external. `--check` compares the committed
 * artifacts without writing, so a stale build fails loudly.
 */
import assert from 'node:assert/strict'
import { readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const check = process.argv.includes('--check')
const clientTarget = join(root, 'client.js')
const hostTarget = join(root, 'index.js')
const clientTemp = join(root, '.client.build.js')
const hostTemp = join(root, '.host.build.js')

/** Bundle one entry to a temporary path so `--check` never mutates committed output. */
async function bundle(entry, outfile, options) {
  await build({ entryPoints: [join(root, entry)], outfile, logLevel: 'silent', legalComments: 'none', ...options })
  return readFile(outfile, 'utf8')
}

try {
  const client = await bundle('src/client.tsx', clientTemp, {
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    banner: {
      js:
        `// Remote Instance ${pkg.version}. Generated by scripts/build.mjs; edit src/.\n` +
        `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => { const module = { exports: {} }; const exports = module.exports;`,
    },
    footer: { js: 'return module.exports; } });' },
  })
  const host = await bundle('src/host.ts', hostTemp, {
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
  })

  if (check) {
    assert.equal(await readFile(clientTarget, 'utf8'), client, 'client.js is stale; run node scripts/build.mjs')
    assert.equal(await readFile(hostTarget, 'utf8'), host, 'index.js is stale; run node scripts/build.mjs')
    console.log(`Artifacts are current: ${pkg.name} (client ${Buffer.byteLength(client)} B, host ${Buffer.byteLength(host)} B)`)
  } else {
    await writeFile(clientTarget, client, 'utf8')
    await writeFile(hostTarget, host, 'utf8')
    console.log(`Built ${pkg.name}: client ${Buffer.byteLength(client)} B, host ${Buffer.byteLength(host)} B`)
  }
} finally {
  await rm(clientTemp, { force: true })
  await rm(hostTemp, { force: true })
}
