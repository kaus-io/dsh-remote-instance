/**
 * 版本一致性检查：`package.json` 是唯一来源，提交产物与文档里的版本必须与它一致。
 * Release 触发时还要比对 tag（`v1.0.0-alpha01` 或裸版本号）。
 *
 * Version consistency: `package.json` is the single source, so the committed
 * build and the docs must agree with it. A release run also compares the tag
 * (`v1.0.0-alpha01` or the bare version).
 */
import { readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

/** 完整 SemVer，含预发布与构建元数据。 / Full SemVer, prerelease and build metadata included. */
const SEMVER = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/
/** 构建产物头部的版本注释。 / The version banner the build writes. */
const BANNER = /^\/\/ Remote Instance (.+?)\. Generated by scripts\/build\.mjs/m
/** 包名，用于定位文档里的固定版本写法。 / Package name used to find pinned versions in docs. */
export const PACKAGE = '@kaus-io/dsh-remote-instance'

/**
 * 校验一组输入并返回问题列表；空数组表示一致。
 * Check one set of inputs and return the problems; an empty array means they agree.
 */
export function versionProblems(input) {
  const problems = []
  const { version, tag } = input
  if (typeof version !== 'string' || !SEMVER.test(version)) {
    problems.push(`package.json version "${String(version)}" is not valid SemVer`)
    return problems
  }

  const banner = BANNER.exec(input.clientSource ?? '')?.[1]
  if (banner === undefined) problems.push('client.js has no build banner; run node scripts/build.mjs')
  else if (banner !== version) problems.push(`client.js was built for "${banner}" but package.json says "${version}"; run node scripts/build.mjs`)

  const pinned = [...String(input.readme ?? '').matchAll(new RegExp(`${PACKAGE.replace(/[./]/g, '\\$&')}@(\\d[^\\s\`)\\]'"<>]*)`, 'g'))].map(match => match[1])
  if (pinned.length === 0) problems.push(`README.md does not show an install command pinned to ${PACKAGE}@${version}`)
  for (const value of pinned) if (value !== version) problems.push(`README.md pins "${value}" but package.json says "${version}"`)

  const heading = /^##\s+(.+)$/m.exec(String(input.changelog ?? ''))?.[1]?.trim()
  const documented = heading === undefined ? undefined : /(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)/.exec(heading)?.[1]
  if (documented === undefined) problems.push('CHANGELOG.md has no "## <version>" entry for the current version')
  else if (documented !== version) problems.push(`CHANGELOG.md starts at "${documented}" but package.json says "${version}"; add the entry`)

  if (tag !== undefined && tag !== version && tag !== `v${version}`) {
    problems.push(`release tag "${tag}" does not match package.json version "${version}"; bump package.json, rebuild, commit, then release v${version}`)
  }
  return problems
}

/** 读取仓库内参与检查的文件。 / Read the files this check inspects. */
export async function readVersionInputs(root, tag) {
  const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  const [clientSource, overview, usage, changelog] = await Promise.all([
    readFile(join(root, 'client.js'), 'utf8'),
    readFile(join(root, 'README.md'), 'utf8'),
    readFile(join(root, 'docs', 'README.md'), 'utf8'),
    readFile(join(root, 'CHANGELOG.md'), 'utf8'),
  ])
  return { version: packageJson.version, clientSource, readme: `${overview}\n${usage}`, changelog, tag }
}

const isMain = process.argv[1] !== undefined && pathToFileURL(process.argv[1]).href === import.meta.url

if (isMain) {
  const args = process.argv.slice(2)
  const tagIndex = args.indexOf('--tag')
  const tag = tagIndex >= 0 ? args[tagIndex + 1] : undefined
  if (tagIndex >= 0 && (tag === undefined || tag === '')) {
    process.stderr.write('--tag needs a release tag value\n')
    process.exitCode = 1
  } else {
    const root = dirname(dirname(fileURLToPath(import.meta.url)))
    const inputs = await readVersionInputs(root, tag)
    const problems = versionProblems(inputs)
    if (problems.length > 0) {
      for (const problem of problems) process.stderr.write(`::error::${problem}\n`)
      process.exitCode = 1
    } else {
      process.stdout.write(`versions agree: ${inputs.version}${tag === undefined ? '' : ` (tag ${tag})`}\n`)
    }
  }
}
